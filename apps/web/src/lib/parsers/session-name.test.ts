import { describe, it, expect } from 'vitest'
import {
  MAX_SESSION_NAME_LENGTH,
  createSessionNameState,
  observeSessionName,
  resolveSessionName,
  truncateSessionName,
} from './session-name'
import type { RawJsonlMessage } from './types'

// Claude Code writes plain-string content too; the parser type only models block arrays.
function user(text: string | Array<{ type: string; text?: string }>, extra: Partial<RawJsonlMessage> = {}): RawJsonlMessage {
  const message = { role: 'user', content: text } as unknown as NonNullable<RawJsonlMessage['message']>
  return { type: 'user', message, ...extra }
}

function summaryLine(text: unknown): RawJsonlMessage {
  return { type: 'summary', summary: text } as RawJsonlMessage
}

function nameFrom(...lines: RawJsonlMessage[]): string | null {
  const state = createSessionNameState()
  for (const line of lines) observeSessionName(state, line)
  return resolveSessionName(state)
}

describe('resolveSessionName', () => {
  it('is null when there is no summary and no user text', () => {
    expect(nameFrom()).toBeNull()
    expect(nameFrom({ type: 'assistant', message: { content: [] } } as RawJsonlMessage)).toBeNull()
  })

  it('uses the summary line over the first user message', () => {
    expect(nameFrom(user('Refactor the parser'), summaryLine('Parser refactor'))).toBe('Parser refactor')
  })

  it('uses the most recent summary line when there are several', () => {
    expect(nameFrom(summaryLine('Old title'), user('hello'), summaryLine('New title'))).toBe('New title')
  })

  it('ignores summary lines whose summary is not a non-empty string', () => {
    expect(nameFrom(summaryLine(42), summaryLine('   '), user('Fallback prompt'))).toBe('Fallback prompt')
    expect(nameFrom(summaryLine(null), summaryLine('Real'))).toBe('Real')
  })

  it('falls back to the first user text message when there is no summary', () => {
    expect(nameFrom(user('First prompt'), user('Second prompt'))).toBe('First prompt')
  })

  it('reads user text from a content array, skipping tool results', () => {
    const toolResult = user([{ type: 'tool_result' }] as never)
    const withText = user([{ type: 'text', text: 'Array prompt' }])
    expect(nameFrom(toolResult, withText)).toBe('Array prompt')
  })

  it('skips meta user lines written by Claude Code', () => {
    const meta = user('Caveat: generated by Claude Code', { isMeta: true })
    expect(nameFrom(meta, user('Real prompt'))).toBe('Real prompt')
  })

  it('skips command wrapper messages', () => {
    const command = user('<command-name>/clear</command-name>')
    const stdout = user('<local-command-stdout>ok</local-command-stdout>')
    expect(nameFrom(command, stdout, user('Actual question'))).toBe('Actual question')
  })

  it('keeps the first user message even if later user messages differ', () => {
    expect(nameFrom(user('one'), user('two'), user('three'))).toBe('one')
  })
})

describe('truncateSessionName', () => {
  it('returns short text unchanged', () => {
    expect(truncateSessionName('Short name')).toBe('Short name')
  })

  it('collapses whitespace and trims', () => {
    expect(truncateSessionName('  line one\n\n  line   two  ')).toBe('line one line two')
  })

  it('returns null for empty or whitespace-only input', () => {
    expect(truncateSessionName(null)).toBeNull()
    expect(truncateSessionName('')).toBeNull()
    expect(truncateSessionName('   \n  ')).toBeNull()
  })

  it('keeps text of exactly the maximum length', () => {
    const exact = 'a'.repeat(MAX_SESSION_NAME_LENGTH)
    expect(truncateSessionName(exact)).toBe(exact)
  })

  it('cuts longer text to the maximum length including the ellipsis', () => {
    const long = 'word '.repeat(40)
    const out = truncateSessionName(long)!
    expect(out.length).toBeLessThanOrEqual(MAX_SESSION_NAME_LENGTH)
    expect(out.endsWith('…')).toBe(true)
    expect(out).not.toMatch(/\s…$/)
  })

  it('truncates a long first user message via resolveSessionName', () => {
    const name = nameFrom(user('x'.repeat(200)))!
    expect(name.length).toBe(MAX_SESSION_NAME_LENGTH)
    expect(name.endsWith('…')).toBe(true)
  })
})
